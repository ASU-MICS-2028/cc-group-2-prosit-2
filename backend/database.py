"""Database access: SQLite on a laptop (no setup), PostgreSQL in the cloud (AWS RDS).

DATABASE_URL set (postgresql://...)  -> PostgreSQL
DATABASE_URL not set                 -> SQLite file DB_PATH (local development, as before)

All queries are written once, with '?' placeholders, and run on both:
- timestamps are text 'YYYY-MM-DD HH:MM:SS' in UTC, made in Python (now_text), so sorting
  and comparing work the same in both databases;
- new ids come back with INSERT ... RETURNING id (not cursor.lastrowid, which PostgreSQL lacks).
The automated tests run against both (see tests/conftest.py and the GitHub workflow).
"""
import config  # noqa: F401  loads .env / AWS secrets before DATABASE_URL is read

import os
import secrets
import sqlite3
from datetime import datetime, timezone

DB_PATH = "healthconnect.db"
DATABASE_URL = os.getenv("DATABASE_URL")

# The few places the two databases differ. Everything else in the schema is shared.
DIALECT = {
    "sqlite": {
        "id": "INTEGER PRIMARY KEY AUTOINCREMENT",
        "now": "(datetime('now'))",
        "real": "REAL",
    },
    "postgres": {
        "id": "INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY",
        "now": "(to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS'))",
        "real": "DOUBLE PRECISION",  # PostgreSQL's REAL is 4 bytes: 38.4 would come back as 38.400001
    },
}

# FHIR ServiceRequest. CHV -> health centre, or nurse -> hospital (parent_id links the chain)
REFERRALS_TABLE = """
CREATE TABLE IF NOT EXISTS referrals (
    id             {id},
    observation_id INTEGER NOT NULL REFERENCES observations(id),
    patient_id     INTEGER NOT NULL REFERENCES patients(id),
    chv_id         INTEGER NOT NULL REFERENCES users(id),   -- CHV who owns the patient
    referred_by    INTEGER REFERENCES users(id),            -- who made this referral (CHV or nurse)
    parent_id      INTEGER REFERENCES referrals(id),        -- set when a nurse escalates
    facility       TEXT NOT NULL,                           -- where the patient is sent
    reason         TEXT,
    status         TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','arrived','completed')),
    outcome        TEXT,
    updated_by     INTEGER REFERENCES users(id),
    created_at     TEXT NOT NULL DEFAULT {now},
    updated_at     TEXT
)
"""

# In creation order: a table's foreign keys only point at tables created before it
TABLES = [
    """
    -- App accounts. Roles: chv, nurse, doctor, ghs, admin (RBAC)
    CREATE TABLE IF NOT EXISTS users (
        id             {id},
        username       TEXT UNIQUE NOT NULL,
        password_hash  TEXT NOT NULL,
        role           TEXT NOT NULL CHECK (role IN ('chv','nurse','doctor','ghs','admin')),
        full_name      TEXT NOT NULL,
        facility       TEXT,
        facility_phone TEXT,
        district       TEXT,  -- for surveillance totals (GHS sees districts, never names)
        active         INTEGER NOT NULL DEFAULT 1,  -- 0 = disabled by admin (kept, never deleted)
        must_change_password INTEGER NOT NULL DEFAULT 0  -- 1 = still on a temporary password
    )""",
    """
    -- FHIR Patient. Registered by a CHV, only after consent (Act 843)
    CREATE TABLE IF NOT EXISTS patients (
        id         {id},
        ref        TEXT UNIQUE NOT NULL,
        chv_id     INTEGER NOT NULL REFERENCES users(id),
        full_name  TEXT NOT NULL,
        age        INTEGER NOT NULL,
        sex        TEXT CHECK (sex IN ('female','male')),
        pregnant   INTEGER NOT NULL DEFAULT 0,
        phone      TEXT,      -- optional; used ONLY for appointment reminders
        community  TEXT,
        district   TEXT,      -- copied from the registering CHV
        consent    INTEGER NOT NULL CHECK (consent = 1),
        created_at TEXT NOT NULL DEFAULT {now}
    )""",
    """
    -- FHIR Observation. One row per check: 'antenatal' or 'general' visit
    CREATE TABLE IF NOT EXISTS observations (
        id                     {id},
        patient_id             INTEGER NOT NULL REFERENCES patients(id),
        recorded_by            INTEGER NOT NULL REFERENCES users(id),
        visit_type             TEXT NOT NULL DEFAULT 'antenatal' CHECK (visit_type IN ('antenatal','general')),
        symptoms               TEXT,      -- general visit: comma-separated symptom codes
        possible_conditions    TEXT,      -- general visit: e.g. 'malaria,meningitis' (not a diagnosis)
        notes                  TEXT,
        gestational_age        INTEGER,
        systolic_bp            INTEGER,
        diastolic_bp           INTEGER,
        weight                 {real},
        hemoglobin             {real},
        body_temp              {real},
        heart_rate             INTEGER,
        previous_complications INTEGER,
        risk_score             {real},
        risk_level             TEXT,
        referral_sent          INTEGER NOT NULL DEFAULT 0,
        created_at             TEXT NOT NULL DEFAULT {now}
    )""",
    REFERRALS_TABLE,
    """
    -- FHIR Appointment. Follow-up booked by a nurse/doctor; SMS reminder ~24h before
    CREATE TABLE IF NOT EXISTS appointments (
        id                  {id},
        patient_id          INTEGER NOT NULL REFERENCES patients(id),
        referral_id         INTEGER NOT NULL REFERENCES referrals(id),
        booked_by           INTEGER NOT NULL REFERENCES users(id),
        facility            TEXT NOT NULL,
        scheduled_at        TEXT NOT NULL,   -- 'YYYY-MM-DD HH:MM' (Ghana time = UTC)
        reason              TEXT,
        status              TEXT NOT NULL DEFAULT 'booked' CHECK (status IN ('booked','attended','missed','cancelled')),
        reminder_status     TEXT,            -- NULL = not sent yet, 'sending' = claimed by a run, then 'sent' / 'failed' / 'no_phone'
        reminder_attempts   INTEGER NOT NULL DEFAULT 0,
        reminder_claimed_at TEXT,
        created_at          TEXT NOT NULL DEFAULT {now}
    )""",
    """
    -- FHIR AuditEvent. Who did what to which record, and when
    CREATE TABLE IF NOT EXISTS access_log (
        id        {id},
        user_id   INTEGER REFERENCES users(id),
        action    TEXT NOT NULL,
        resource  TEXT,
        timestamp TEXT NOT NULL DEFAULT {now}
    )""",
]


def is_postgres():
    return bool(DATABASE_URL)


def now_text():
    """The current UTC time in the format every timestamp column uses."""
    return datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M:%S")


class PostgresConnection:
    """Makes a psycopg connection behave like the sqlite3 one the code was written for:
    '?' placeholders, rows readable as row["column"], execute() straight on the connection."""

    def __init__(self, raw):
        self.raw = raw

    def execute(self, sql, params=None):
        if params:
            # psycopg uses %s; a literal % (as in LIKE 'Demo%') must then be written %%
            return self.raw.execute(sql.replace("%", "%%").replace("?", "%s"), params)
        return self.raw.execute(sql)

    def commit(self):
        self.raw.commit()

    def rollback(self):
        self.raw.rollback()

    def close(self):
        self.raw.close()


def connect_postgres():
    import psycopg
    from psycopg.rows import dict_row

    global DATABASE_URL
    try:
        return psycopg.connect(DATABASE_URL, row_factory=dict_row, connect_timeout=10)
    except psycopg.OperationalError:
        if not os.getenv("DB_SECRET_ID"):
            raise
        # AWS may have rotated the database password: read the secret again and retry once
        config.load_database_url()
        DATABASE_URL = os.environ["DATABASE_URL"]
        return psycopg.connect(DATABASE_URL, row_factory=dict_row, connect_timeout=10)


def get_db():
    # One connection per request; rows behave like dicts (row["name"])
    if is_postgres():
        return PostgresConnection(connect_postgres())
    conn = sqlite3.connect(DB_PATH)
    conn.row_factory = sqlite3.Row
    conn.execute("PRAGMA foreign_keys = ON")
    return conn


def init_db():
    dialect = DIALECT["postgres" if is_postgres() else "sqlite"]
    conn = get_db()
    for table in TABLES:
        conn.execute(table.format(**dialect))
    migrate(conn)
    conn.commit()
    conn.close()


def column_exists(conn, table, column):
    if is_postgres():
        return conn.execute(
            "SELECT 1 FROM information_schema.columns WHERE table_schema = current_schema() "
            "AND table_name = ? AND column_name = ?", (table, column)).fetchone() is not None
    return column in [row["name"] for row in conn.execute(f"PRAGMA table_info({table})")]


def add_column_if_missing(conn, table, column, definition):
    if column_exists(conn, table, column):
        return False
    conn.execute(f"ALTER TABLE {table} ADD COLUMN {column} {definition}")
    return True


def migrate(conn):
    # Columns added after the first version. A new database already has them all.
    add_column_if_missing(conn, "appointments", "reminder_attempts", "INTEGER NOT NULL DEFAULT 0")
    add_column_if_missing(conn, "appointments", "reminder_claimed_at", "TEXT")
    if is_postgres():
        return  # PostgreSQL databases start from the current schema; the steps below are for old laptop files

    # Old local SQLite files, from before general visits existed.
    # Their patients were all antenatal, so they are marked female + pregnant.
    if add_column_if_missing(conn, "patients", "sex", "TEXT CHECK (sex IN ('female','male'))"):
        add_column_if_missing(conn, "patients", "pregnant", "INTEGER NOT NULL DEFAULT 0")
        conn.execute("UPDATE patients SET sex = 'female', pregnant = 1")
    add_column_if_missing(conn, "patients", "phone", "TEXT")
    add_column_if_missing(conn, "users", "district", "TEXT")
    add_column_if_missing(conn, "users", "active", "INTEGER NOT NULL DEFAULT 1")
    add_column_if_missing(conn, "users", "must_change_password", "INTEGER NOT NULL DEFAULT 0")
    if add_column_if_missing(conn, "patients", "district", "TEXT"):
        # Existing patients take their CHV's district
        conn.execute("UPDATE patients SET district = (SELECT district FROM users WHERE users.id = patients.chv_id)")
    add_column_if_missing(conn, "observations", "visit_type", "TEXT NOT NULL DEFAULT 'antenatal'")
    add_column_if_missing(conn, "observations", "symptoms", "TEXT")
    add_column_if_missing(conn, "observations", "possible_conditions", "TEXT")
    add_column_if_missing(conn, "observations", "notes", "TEXT")

    # Old referrals table allowed only one referral per check (UNIQUE observation_id).
    # Escalation needs two, so rebuild the table and copy the rows across.
    old_sql = conn.execute("SELECT sql FROM sqlite_master WHERE name = 'referrals'").fetchone()["sql"]
    if "observation_id INTEGER UNIQUE" in old_sql:
        conn.execute("ALTER TABLE referrals RENAME TO referrals_old")
        conn.execute(REFERRALS_TABLE.format(**DIALECT["sqlite"]))
        conn.execute("""
            INSERT INTO referrals (id, observation_id, patient_id, chv_id, referred_by, facility,
                                   status, outcome, updated_by, created_at, updated_at)
            SELECT id, observation_id, patient_id, chv_id, chv_id, facility,
                   status, outcome, updated_by, created_at, updated_at
            FROM referrals_old
        """)
        conn.execute("DROP TABLE referrals_old")


def new_patient_ref(conn):
    # Random reference like HC-3FA21C, never derived from the name.
    # 6 hex characters = 16.7 million options; pick again in the rare case it is taken.
    while True:
        ref = "HC-" + secrets.token_hex(3).upper()
        if not conn.execute("SELECT 1 FROM patients WHERE ref = ?", (ref,)).fetchone():
            return ref


def log_access(conn, user_id, action, resource=None):
    conn.execute(
        "INSERT INTO access_log (user_id, action, resource, timestamp) VALUES (?, ?, ?, ?)",
        (user_id, action, resource, now_text()),
    )
