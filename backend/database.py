def is_postgres():
    return bool(DATABASE_URL)


def now_text():
    """The current UTC time in the format every timestamp column uses."""
    return datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M:%S")


class PostgresConnection:
    """Makes a psycopg connection behave like the sqlite3 one the code was written for:
    '?' placeholders, rows readable as row["column"], execute() straight on the connection."""

    def __init__(self, raw):
        self.raw = raw

    def execute(self, sql, params=None):
        if params:
            # psycopg uses %s; a literal % (as in LIKE 'Demo%') must then be written %%
            return self.raw.execute(sql.replace("%", "%%").replace("?", "%s"), params)
        return self.raw.execute(sql)

    def commit(self):
        self.raw.commit()

    def rollback(self):
        self.raw.rollback()

    def close(self):
        self.raw.close()


def connect_postgres():
    import psycopg
    from psycopg.rows import dict_row

    global DATABASE_URL
    try:
        return psycopg.connect(DATABASE_URL, row_factory=dict_row, connect_timeout=10)
    except psycopg.OperationalError:
        if not os.getenv("DB_SECRET_ID"):
            raise
        # AWS may have rotated the database password: read the secret again and retry once
        config.load_database_url()
        DATABASE_URL = os.environ["DATABASE_URL"]
        return psycopg.connect(DATABASE_URL, row_factory=dict_row, connect_timeout=10)


def get_db():
    # One connection per request; rows behave like dicts (row["name"])
    if is_postgres():
        return PostgresConnection(connect_postgres())
    conn = sqlite3.connect(DB_PATH)
    conn.row_factory = sqlite3.Row
    conn.execute("PRAGMA foreign_keys = ON")
    return conn


def init_db():
    dialect = DIALECT["postgres" if is_postgres() else "sqlite"]
    conn = get_db()
    for table in TABLES:
        conn.execute(table.format(**dialect))
    migrate(conn)
    add_starter_drugs(conn)
    add_starter_lessons(conn)
    conn.commit()
    conn.close()


def add_starter_drugs(conn):
    # Reference data, so real deployments get it too. Existing drugs are left as they are.
    for name, unit, reorder_level, condition in STARTER_DRUGS:
        conn.execute(
            "INSERT INTO drugs (name, unit, default_reorder_level, condition) VALUES (?, ?, ?, ?) "
            "ON CONFLICT (name) DO NOTHING",
            (name, unit, reorder_level, condition),
        )


def add_starter_lessons(conn):
    # Existing lessons, and any review of them, are left as they are.
    for topic, title, body in STARTER_LESSONS:
        conn.execute("INSERT INTO lessons (topic, title, body, language) VALUES (?, ?, ?, 'en') "
                     "ON CONFLICT (title, language) DO NOTHING", (topic, title, body))


def column_exists(conn, table, column):
    if is_postgres():
        return conn.execute(
            "SELECT 1 FROM information_schema.columns WHERE table_schema = current_schema() "
            "AND table_name = ? AND column_name = ?", (table, column)).fetchone() is not None
    return column in [row["name"] for row in conn.execute(f"PRAGMA table_info({table})")]


def add_column_if_missing(conn, table, column, definition):
    if column_exists(conn, table, column):
        return False
    conn.execute(f"ALTER TABLE {table} ADD COLUMN {column} {definition}")
    return True


def allow_all_roles(conn):
    """Databases made before the pharmacist role only allow the old roles: widen the CHECK."""
    if is_postgres():
        row = conn.execute(
            "SELECT conname, pg_get_constraintdef(oid) AS def FROM pg_constraint "
            "WHERE conrelid = 'users'::regclass AND contype = 'c' AND pg_get_constraintdef(oid) LIKE '%role%'"
        ).fetchone()
        if row and "pharmacist" not in row["def"]:
            conn.execute(f'ALTER TABLE users DROP CONSTRAINT "{row["conname"]}"')
            conn.execute(f"ALTER TABLE users ADD CONSTRAINT users_role_check CHECK ({ROLE_CHECK})")
        return

    # SQLite cannot change a CHECK, so the table is rebuilt: copy the rows into a new one.
    # Foreign keys are switched off meanwhile, so other tables' links to users(id) survive.
    if "pharmacist" in conn.execute("SELECT sql FROM sqlite_master WHERE name = 'users'").fetchone()["sql"]:
        return
    conn.commit()
    conn.execute("PRAGMA foreign_keys = OFF")
    conn.execute(USERS_TABLE.format(table="users_new", **DIALECT["sqlite"]))
    columns = "id, username, password_hash, role, full_name, facility, facility_phone, district, active, must_change_password"
    conn.execute(f"INSERT INTO users_new ({columns}) SELECT {columns} FROM users")
    conn.execute("DROP TABLE users")
    conn.execute("ALTER TABLE users_new RENAME TO users")
    conn.commit()
    conn.execute("PRAGMA foreign_keys = ON")


def migrate(conn):
    # Columns added after the first version. A new database already has them all.
    add_column_if_missing(conn, "appointments", "reminder_attempts", "INTEGER NOT NULL DEFAULT 0")
    add_column_if_missing(conn, "appointments", "reminder_claimed_at", "TEXT")
    # How to remind the patient: many can speak but not read their language, so SMS is not always right
    add_column_if_missing(conn, "patients", "reminder_method",
                          "TEXT NOT NULL DEFAULT 'sms' CHECK (reminder_method IN ('sms','chv'))")
    # Voice-call reminders were dropped (team decision): those patients are reminded by the CHV
    conn.execute("UPDATE patients SET reminder_method = 'chv' WHERE reminder_method = 'voice'")
    add_column_if_missing(conn, "patients", "language", "TEXT")
    add_column_if_missing(conn, "users", "facility_manager", "INTEGER NOT NULL DEFAULT 0")
    # Community health alerts: patients must agree before they get them (purpose limitation)
    add_column_if_missing(conn, "patients", "health_alerts", "INTEGER NOT NULL DEFAULT 0")
    # Child immunisation tracking (immunisation.py)
    add_column_if_missing(conn, "patients", "birth_date", "TEXT")
    # Emergency auto-escalation (escalation.py)
    add_column_if_missing(conn, "referrals", "auto_escalated_at", "TEXT")
    # Height (cm), asked for in the brief's vital signs
    add_column_if_missing(conn, "observations", "height", DIALECT["postgres" if is_postgres() else "sqlite"]["real"])
    if is_postgres():
        allow_all_roles(conn)
        return  # PostgreSQL databases start from the current schema; the steps below are for old laptop files

    # Old local SQLite files, from before general visits existed.
    # Their patients were all antenatal, so they are marked female + pregnant.
    if add_column_if_missing(conn, "patients", "sex", "TEXT CHECK (sex IN ('female','male'))"):
        add_column_if_missing(conn, "patients", "pregnant", "INTEGER NOT NULL DEFAULT 0")
        conn.execute("UPDATE patients SET sex = 'female', pregnant = 1")
    add_column_if_missing(conn, "patients", "phone", "TEXT")
    add_column_if_missing(conn, "users", "district", "TEXT")
    add_column_if_missing(conn, "users", "active", "INTEGER NOT NULL DEFAULT 1")
    add_column_if_missing(conn, "users", "must_change_password", "INTEGER NOT NULL DEFAULT 0")
    if add_column_if_missing(conn, "patients", "district", "TEXT"):
        # Existing patients take their CHV's district
        conn.execute("UPDATE patients SET district = (SELECT district FROM users WHERE users.id = patients.chv_id)")
    add_column_if_missing(conn, "observations", "visit_type", "TEXT NOT NULL DEFAULT 'antenatal'")
    add_column_if_missing(conn, "observations", "symptoms", "TEXT")
    add_column_if_missing(conn, "observations", "possible_conditions", "TEXT")
    add_column_if_missing(conn, "observations", "notes", "TEXT")

    # Old referrals table allowed only one referral per check (UNIQUE observation_id).
    # Escalation needs two, so rebuild the table and copy the rows across.
    old_sql = conn.execute("SELECT sql FROM sqlite_master WHERE name = 'referrals'").fetchone()["sql"]
    if "observation_id INTEGER UNIQUE" in old_sql:
        conn.execute("ALTER TABLE referrals RENAME TO referrals_old")
        conn.execute(REFERRALS_TABLE.format(**DIALECT["sqlite"]))
        conn.execute("""
            INSERT INTO referrals (id, observation_id, patient_id, chv_id, referred_by, facility,
                                   status, outcome, updated_by, created_at, updated_at)
            SELECT id, observation_id, patient_id, chv_id, chv_id, facility,
                   status, outcome, updated_by, created_at, updated_at
            FROM referrals_old
        """)
        conn.execute("DROP TABLE referrals_old")

    # Last, once the users table has all its columns
    allow_all_roles(conn)


def new_patient_ref(conn):
    # Random reference like HC-3FA21C, never derived from the name.
    # 6 hex characters = 16.7 million options; pick again in the rare case it is taken.
    while True:
        ref = "HC-" + secrets.token_hex(3).upper()
        if not conn.execute("SELECT 1 FROM patients WHERE ref = ?", (ref,)).fetchone():
            return ref


def log_access(conn, user_id, action, resource=None):
    conn.execute(
        "INSERT INTO access_log (user_id, action, resource, timestamp) VALUES (?, ?, ?, ?)",
        (user_id, action, resource, now_text()),
    )
