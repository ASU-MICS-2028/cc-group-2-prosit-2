# The few places the two databases differ. Everything else in the schema is shared.
DIALECT = {
    "sqlite": {
        "id": "INTEGER PRIMARY KEY AUTOINCREMENT",
        "now": "(datetime('now'))",
        "real": "REAL",
    },
    "postgres": {
        "id": "INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY",
        "now": "(to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS'))",
        "real": "DOUBLE PRECISION",  # PostgreSQL's REAL is 4 bytes: 38.4 would come back as 38.400001
    },
}

